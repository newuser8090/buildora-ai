describe("generatePageFile — page-level metadata", () => {
  it("uses seoTitle for the Google title and page.title as fallback", () => {
    const project = makeProject({
      pages: [{
        id: "p1", title: "Home", slug: "/",
        meta: { seoTitle: "Google Title" },
        sections: [{ id: "s1", type: "hero", order: 1, visible: true, props: { headline: "Hello" }, styles: {} }],
      }],
    });
    const file = generatePageFile(project, project.pages[0], routesOf(project), undefined);
    expect(file.content).toContain('title: "Google Title"');
  });

  it("falls back deterministically: seoTitle → title → page.title", () => {
    const project = makeProject();
    const file = generatePageFile(project, project.pages[0], routesOf(project), undefined);
    expect(file.content).toContain('title: "Home"');
  });

  it("emits description only when available", () => {
    const withDesc = makeProject({
      pages: [{
        id: "p1", title: "Home", slug: "/",
        meta: { title: "Home", description: "A page description" },
        sections: [{ id: "s1", type: "hero", order: 1, visible: true, props: { headline: "Hello" }, styles: {} }],
      }],
    });
    const file = generatePageFile(withDesc, withDesc.pages[0], routesOf(withDesc), undefined);
    expect(file.content).toContain('description: "A page description"');

    const plain = makeProject();
    const plainFile = generatePageFile(plain, plain.pages[0], routesOf(plain), undefined);
    expect(plainFile.content).not.toMatch(/^  description: /m);
  });

  it("emits canonical alternates when a canonical URL is set", () => {
    const project = makeProject({
      pages: [{
        id: "p1", title: "Home", slug: "/",
        meta: { canonicalUrl: "https://example.com/" },
        sections: [{ id: "s1", type: "hero", order: 1, visible: true, props: { headline: "Hello" }, styles: {} }],
      }],
    });
    const file = generatePageFile(project, project.pages[0], routesOf(project), undefined);
    expect(file.content).toContain('alternates: { canonical: "https://example.com/" }');
  });

  it("emits robots index:false only when the page is hidden", () => {
    const hidden = makeProject({
      pages: [{
        id: "p1", title: "Home", slug: "/",
        meta: { index: false },
        sections: [{ id: "s1", type: "hero", order: 1, visible: true, props: { headline: "Hello" }, styles: {} }],
      }],
    });
    const file = generatePageFile(hidden, hidden.pages[0], routesOf(hidden), undefined);
    expect(file.content).toContain("robots: { index: false }");

    const plain = makeProject();
    const plainFile = generatePageFile(plain, plain.pages[0], routesOf(plain), undefined);
    expect(plainFile.content).not.toContain("robots:");
  });

  it("emits openGraph with title fallback and optional description/url/images", () => {
    const project = makeProject({
      assets: [makeAsset({ id: "share" })],
      pages: [{
        id: "p1", title: "Home", slug: "/",
        meta: {
          seoTitle: "Google Title",
          description: "A page description",
          socialTitle: "Share Title",
          socialDescription: "Share desc",
          socialImage: { assetId: "share" },
          canonicalUrl: "https://example.com/",
        },
        sections: [{ id: "s1", type: "hero", order: 1, visible: true, props: { headline: "Hello" }, styles: {} }],
      }],
    });
    const manifest = buildExportAssetManifest(project);
    expect(manifest.valid).toBe(true);
    const file = generatePageFile(project, project.pages[0], routesOf(project), manifest);
    expect(file.content).toContain("openGraph:");
    expect(file.content).toContain('title: "Share Title"');
    expect(file.content).toContain('description: "Share desc"');
    expect(file.content).toContain('url: "https://example.com/"');
    expect(file.content).toContain('images: ["/assets/share.png"]');
  });

  it("omits social image when the asset is missing from the manifest", () => {
    const project = makeProject({
      pages: [{
        id: "p1", title: "Home", slug: "/",
        meta: { socialImage: { assetId: "missing" }, socialTitle: "T" },
        sections: [{ id: "s1", type: "hero", order: 1, visible: true, props: { headline: "Hello" }, styles: {} }],
      }],
    });
    const file = generatePageFile(project, project.pages[0], routesOf(project), undefined);
    expect(file.content).not.toContain("images:");
  });
});
