// ---------------------------------------------------------------------------

describe("generateLayout — site-level metadata", () => {
  it("falls back to project name and a default description", () => {
    const file = generateLayout({ projectName: "My Project" });
    expect(file.path).toBe("app/layout.tsx");
    expect(file.content).toContain('title: "My Project"');
    expect(file.content).toContain('description: "Generated by Buildora"');
    expect(file.content).toContain('lang="en"');
  });

  it("emits site settings metadata when present", () => {
    const file = generateLayout({
      projectName: "My Project",
      siteSettings: {
        siteName: "Brand Name",
        siteDescription: "Tagline",
        language: "fr",
        faviconPublicPath: "/assets/icon.png",
        themeColor: "#7c5cfc",
        seoTitle: "Brand | Search Title",
      },
    });
    expect(file.content).toContain('title: "Brand | Search Title"');
    expect(file.content).toContain('description: "Tagline"');
    expect(file.content).toContain('lang="fr"');
    expect(file.content).toContain('icons: [{ rel: "icon", url: "/assets/icon.png" }]');
    expect(file.content).toContain('themeColor: "#7c5cfc"');
  });

  it("prefers seoDescription over siteDescription when only SEO is set", () => {
    const file = generateLayout({
      projectName: "P",
      siteSettings: { seoDescription: "SEO summary" },
    });
    expect(file.content).toContain('description: "SEO summary"');
  });

  it("emits robots only when the user opted out of indexing", () => {
    const hidden = generateLayout({
      projectName: "P",
      siteSettings: { robotsIndex: false },
    });
    expect(hidden.content).toContain("robots: { index: false, follow: true }");

    const defaulted = generateLayout({ projectName: "P", siteSettings: { siteName: "X" } });
    expect(defaulted.content).not.toContain("robots:");
  });

  it("escapes quotes and backslashes in metadata values", () => {
    const file = generateLayout({
      projectName: "Test",
      siteSettings: { siteName: 'He said "hi" \\ ok', seoTitle: 'Title "quoted"' },
    });
    expect(file.content).toContain('\\"');
    expect(file.content).not.toContain('title: "He said "hi""');
  });
});

