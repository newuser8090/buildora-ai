import { describe, it, expect } from "vitest";
import { generateLayout } from "../generators/layout-generator";
import { generatePageFile } from "../generators/page-generator";
import { buildExportAssetManifest } from "../generators/asset-export-manifest";
import { computePageRoutes } from "@/features/routing/routes";
import type { Project } from "@/types/project";
import type { Asset } from "@/features/assets/types";

function makeAsset(overrides?: Partial<Asset>): Asset {
  return {
    id: "a1", name: "share.png", type: "image", mimeType: "image/png", extension: ".png",
    size: 1024,
    source: { type: "data-url", value: "data:image/png;base64,iVBORw0KGgo=" },
    createdAt: "2026-01-01T00:00:00.000Z",
    ...overrides,
  };
}

function routesOf(project: Project) {
  return computePageRoutes(project.pages);
}

function makeProject(overrides?: Partial<Project>): Project {
  return {
    id: "proj-1", name: "Test Site",
    theme: {
      palette: {
        background: "#fff", foreground: "#000", primary: "#7c5cfc",
        primaryForeground: "#fff", secondary: "#f5f5f5", secondaryForeground: "#000",
        muted: "#f5f5f5", mutedForeground: "#737373", accent: "#7c5cfc",
        accentForeground: "#fff", border: "#e5e5e5", card: "#fff", cardForeground: "#000",
      },
      typography: { fontFamily: "sans-serif", headingFont: "sans-serif", baseSize: "16px", scale: 1.25 },
      spacing: { sectionPadding: "5rem 0", containerMaxWidth: "1120px", gap: "1.5rem" },
      radius: { sm: "0.375rem", md: "0.5rem", lg: "0.75rem", xl: "1rem", full: "9999px" },
      shadows: { sm: "0 1px 2px rgba(0,0,0,0.05)", md: "0 4px 6px rgba(0,0,0,0.07)", lg: "0 10px 15px rgba(0,0,0,0.1)", xl: "0 20px 25px rgba(0,0,0,0.15)" },
    },
    assets: [],
    pages: [
      {
        id: "p1", title: "Home", slug: "/",
        sections: [
          { id: "s1", type: "hero", order: 1, visible: true, props: { headline: "Hello", primaryCta: { text: "Go", href: "#" } }, styles: {} },
        ],
      },
    ],
    createdAt: "2026-01-01T00:00:00.000Z",
    updatedAt: "2026-01-01T00:00:00.000Z",
    ...overrides,
  };
}

